"""Check our possession/lineup parse against pbpstats' independent parse.

Two checks, written to reports/validation_<season>.md:
  * per game and team: possession counts and points vs pbpstats get-games
  * per player: on-court offensive/defensive possessions and plus-minus vs get-totals
"""

from __future__ import annotations

import argparse

import numpy as np
import pandas as pd

from src import config, ingest

OFF = [f"off{i}" for i in range(1, 6)]
DEF = [f"def{i}" for i in range(1, 6)]


def player_on_court(poss: pd.DataFrame) -> pd.DataFrame:
    """Per-player on-court possessions and points for/against."""
    o = poss.melt(id_vars=["poss", "points"], value_vars=OFF, value_name="player_id")
    d = poss.melt(id_vars=["poss", "points"], value_vars=DEF, value_name="player_id")
    o = o.groupby("player_id")[["poss", "points"]].sum().rename(
        columns={"poss": "off_poss", "points": "pts_for"})
    d = d.groupby("player_id")[["poss", "points"]].sum().rename(
        columns={"poss": "def_poss", "points": "pts_against"})
    out = o.join(d, how="outer").fillna(0)
    out["plus_minus"] = out.pts_for - out.pts_against
    return out


def game_checks(poss: pd.DataFrame, season: str) -> pd.DataFrame:
    games = ingest.pbpstats_games(season)
    ours = poss.groupby(["game_id", "off_team"])[["poss", "points"]].sum().reset_index()
    rows = []
    for g in games.itertuples(index=False):
        for side in ("Home", "Away"):
            t = int(getattr(g, f"{side}TeamId"))
            m = ours[(ours.game_id == g.GameId) & (ours.off_team == t)]
            rows.append({"game_id": g.GameId, "team": t,
                         "poss_ours": int(m.poss.sum()),
                         "poss_pbp": getattr(g, f"{side}Possessions"),
                         "pts_ours": int(m.points.sum()),
                         "pts_pbp": getattr(g, f"{side}Points")})
    df = pd.DataFrame(rows)
    df["poss_diff"] = df.poss_ours - df.poss_pbp
    df["pts_diff"] = df.pts_ours - df.pts_pbp
    return df


def player_checks(poss: pd.DataFrame, season: str) -> pd.DataFrame:
    tot = ingest.pbpstats_totals(season)
    tot = tot.groupby("EntityId").agg(name=("Name", "first"), off_poss_pbp=("OffPoss", "sum"),
                                      def_poss_pbp=("DefPoss", "sum"),
                                      pm_pbp=("PlusMinus", "sum"))
    ours = player_on_court(poss)
    df = tot.join(ours, how="outer")
    df.index.name = "player_id"
    return df.reset_index()


def report(season: str) -> str:
    poss = pd.read_parquet(config.PROCESSED / f"possessions_{season}.parquet")
    g = game_checks(poss, season)
    p = player_checks(poss, season)
    pm = p.dropna(subset=["off_poss", "off_poss_pbp"])
    big = pm[pm.off_poss_pbp >= 500]
    hugo = p[p.player_id == config.load()["player"]["id"]].iloc[0]

    def pct(x):
        return f"{100 * x:.1f}%"

    lines = [
        f"# Parse validation, {season}",
        "",
        "Generated by `python -m src.validate`. Reference: api.pbpstats.com (independent parse).",
        "",
        "## Game level (team-games)",
        "",
        f"- Team-games: {len(g)}; our total possessions {g.poss_ours.sum():,} vs pbpstats "
        f"{g.poss_pbp.sum():,} ({g.poss_diff.sum():+,})",
        f"- Possession count exact: {pct((g.poss_diff == 0).mean())}; within ±1: "
        f"{pct((g.poss_diff.abs() <= 1).mean())}; "
        f"within ±2: {pct((g.poss_diff.abs() <= 2).mean())}",
        f"- Points exact: {pct((g.pts_diff == 0).mean())} (max abs diff {g.pts_diff.abs().max()})",
        "",
        "## Player level",
        "",
        f"- Players in both sources: {len(pm)}; with ≥500 off. possessions: {len(big)}",
        f"- Off. possessions: corr {np.corrcoef(pm.off_poss, pm.off_poss_pbp)[0, 1]:.4f}, "
        f"median abs diff {np.median(np.abs(pm.off_poss - pm.off_poss_pbp)):.0f}",
        f"- Def. possessions: corr {np.corrcoef(pm.def_poss, pm.def_poss_pbp)[0, 1]:.4f}, "
        f"median abs diff {np.median(np.abs(pm.def_poss - pm.def_poss_pbp)):.0f}",
        f"- Note: pbpstats' summed player DefPoss is "
        f"{pm.def_poss_pbp.sum() / pm.off_poss_pbp.sum() - 1:+.2%} vs its OffPoss (OffPoss "
        "equals 5x its game totals), so its DefPoss uses a different convention; compare "
        "on OffPoss.",
        f"- Plus-minus exact: {pct((pm.plus_minus == pm.pm_pbp).mean())}; "
        f"median abs diff {np.median(np.abs(pm.plus_minus - pm.pm_pbp)):.0f}; "
        f"max abs diff {np.abs(pm.plus_minus - pm.pm_pbp).max():.0f}",
        "",
        "## Hugo Gonzalez",
        "",
        "| | ours | pbpstats |",
        "|---|---|---|",
        f"| Off. possessions | {hugo.off_poss:.0f} | {hugo.off_poss_pbp:.0f} |",
        f"| Def. possessions | {hugo.def_poss:.0f} | {hugo.def_poss_pbp:.0f} |",
        f"| Plus-minus | {hugo.plus_minus:+.0f} | {hugo.pm_pbp:+.0f} |",
        "",
        "## Largest player discrepancies (plus-minus)",
        "",
        (pm.assign(pm_diff=pm.plus_minus - pm.pm_pbp)
           .reindex(columns=["player_id", "name", "off_poss", "off_poss_pbp", "plus_minus",
                             "pm_pbp", "pm_diff"])
           .sort_values("pm_diff", key=abs, ascending=False).head(10)
           .to_markdown(index=False, floatfmt=".0f")),
    ]
    text = "\n".join(lines) + "\n"
    (config.REPORTS / f"validation_{season}.md").write_text(text)
    g.to_csv(config.PROCESSED / f"validation_games_{season}.csv", index=False)
    return text


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--season", default=config.load()["seasons"]["primary"])
    print(report(ap.parse_args().season))


if __name__ == "__main__":
    main()
